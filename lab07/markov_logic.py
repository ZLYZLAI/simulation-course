"""
markov_logic.py - вся математика и логика непрерывной цепи Маркова (НВЦМ).
Реализую трёхсостоянную модель погоды с непрерывным временем:
    0 - Ясно
    1 - Облачно
    2 - Пасмурно
Единица времени = 1 день. Время непрерывное: погода может смениться
несколько раз в день или оставаться неизменной несколько дней подряд.
Математическая основа:
    - Матрица интенсивностей Q (инфинитезимальный генератор):
        q_ij > 0 при i != j  - интенсивность перехода из i в j (1/день)
        q_ii = -sum(q_ij, j!=i) - суммарная интенсивность выхода из i
        Каждая строка суммируется в 0: sum_j(q_ij) = 0
    - Время пребывания в состоянии i: T_i ~ Exp(lambda_i), lambda_i = |q_ii|
        Математическое ожидание: E[T_i] = 1 / lambda_i
    - Вероятность следующего состояния j (при выходе из i):
        p_ij = q_ij / lambda_i  (j != i)
    - Стационарное распределение pi: pi * Q = 0,  sum(pi) = 1

Матрица Q по умолчанию:

    Q = [[-0.4,  0.3,  0.1],
         [ 0.4, -0.8,  0.4],
         [ 0.1,  0.4, -0.5]]

Стационарное распределение: pi_0 = 8/21, pi_1 = 19/63, pi_2 = 20/63.
"""

import numpy as np
import csv
import os
from datetime import datetime


# ===========================
# Основной класс модели

class MarkovWeatherModel:
    """
    Непрерывная цепь Маркова (НВЦМ) для трёхсостоянной модели погоды.

    Я использую классический алгоритм Next-Event Simulation:
    в состоянии i генерирую экспоненциально распределённое время пребывания,
    затем выбираю следующее состояние пропорционально интенсивностям q_ij.
    """

    # Названия состояний (для отображения и экспорта в CSV)
    STATE_NAMES = ['Ясно', 'Облачно', 'Пасмурно']

    # Количество состояний
    N = 3

    def __init__(self):
        # Внедиагональные интенсивности по умолчанию - из лекционных слайдов.
        # _off_diag[i][j] = lambda_ij - скорость перехода из i в j (j != i).
        # Диагональные элементы здесь нулевые; реальная диагональ Q
        # вычисляется в _build_Q() как -sum строки.
        #
        # lambda_01 = 0.3: из «Ясно» в «Облачно» - 0.3 перехода/день
        # lambda_02 = 0.1: из «Ясно» в «Пасмурно» - 0.1 перехода/день
        # lambda_10 = 0.4: из «Облачно» в «Ясно» - 0.4 перехода/день
        # lambda_12 = 0.4: из «Облачно» в «Пасмурно» - 0.4 перехода/день
        # lambda_20 = 0.1: из «Пасмурно» в «Ясно» - 0.1 перехода/день
        # lambda_21 = 0.4: из «Пасмурно» в «Облачно» - 0.4 перехода/день
        self._off_diag = np.array([
            [0.0, 0.3, 0.1],  # из «Ясно»
            [0.4, 0.0, 0.4],  # из «Облачно»
            [0.1, 0.4, 0.0],  # из «Пасмурно»
        ], dtype=float)

        # Строю полную Q-матрицу (с диагональными элементами)
        self._build_Q()

        # Инициализирую переменные симуляции
        self.reset()

    # --------------------------
    # Управление матрицей Q

    def _build_Q(self):
        """
        Строю полную матрицу Q из внедиагональных интенсивностей.
        Диагональный элемент q_ii - суммарная интенсивность выхода из состояния i,
        взятая с минусом (условие нулевой суммы строки):

            q_ii = -sum(q_ij для j != i)

        Это обязательное свойство инфинитезимального генератора НВЦМ:
        сумма каждой строки Q равна нулю:  sum_j(q_ij) = 0.

        Физический смысл q_ii:
            |q_ii| = lambda_i - суммарная интенсивность (скорость) покидания
            состояния i. Среднее время пребывания: E[T_i] = 1 / lambda_i.
        """
        # Копирую внедиагональные значения
        self.Q = self._off_diag.copy()

        # Диагональный элемент = минус сумма всех остальных в строке.
        # np.sum(_off_diag[i, :]) суммирует всю строку; диагональ _off_diag = 0,
        # поэтому результат равен сумме только внедиагональных элементов.
        for i in range(self.N):
            self.Q[i, i] = -np.sum(self._off_diag[i, :])

    def set_intensities(self, off_diag_matrix):
        """
        Устанавливаю новую матрицу интенсивностей (только внедиагональные элементы).

        Параметры:
            off_diag_matrix: массив 3x3, где q_ij >= 0 при i != j.
                Диагональные элементы игнорируются и перевычисляются.

        Отрицательные значения обнуляются: интенсивность не может быть < 0.
        """
        mat = np.array(off_diag_matrix, dtype=float)

        # Интенсивности не могут быть отрицательными
        mat = np.maximum(mat, 0.0)

        # Диагональ обнуляю - она вычислится автоматически в _build_Q()
        np.fill_diagonal(mat, 0.0)

        self._off_diag = mat
        self._build_Q()

    def get_Q_display(self):
        """
        Возвращаю копию Q-матрицы для отображения в GUI.
        Копия нужна, чтобы внешний код не мог случайно изменить матрицу модели.
        """
        return self.Q.copy()

    def get_off_diag_display(self):
        """
        Возвращаю внедиагональные интенсивности для инициализации полей ввода.
        """
        return self._off_diag.copy()

    # -------------------------
    # Управление симуляцией

    def reset(self):
        """
        Сбрасываю симуляцию в начальное состояние.
        Начинаю с состояния 0 (Ясно), обнуляю все счётчики и историю.
        """
        # Текущее состояние: начинаю с «Ясно» (индекс 0)
        self.current_state = 0

        # Суммарное прошедшее модельное время в днях (вещественное число).
        # Накапливается как сумма всех случайных времён пребывания T_i ~ Exp(lambda_i).
        self.total_time = 0.0

        # Число совершённых переходов (= число записей в history).
        self.n_transitions = 0

        # История переходов: список кортежей (t_вход, состояние, длительность).
        # Пример: (1.73, 2, 0.84) = «вошли в «Пасмурно» в момент 1.73 дня,
        # пробыли там 0.84 дня».
        # t_выход = t_вход + длительность.
        self.history = []

        # Суммарное непрерывное время, проведённое в каждом состоянии (в днях).
        # time_in_state[i] += holding_time при каждом выходе из состояния i.
        self.time_in_state = np.zeros(self.N)

        # Бегущие доли накопленного времени - для графика сходимости.
        # running_fractions[i][k] = time_in_state[i] / total_time после k-го перехода.
        # Согласно эргодической теореме, при большом числе переходов:
        #     running_fractions[i][-1]  -->  pi[i]  (стационарное распределение).
        self.running_fractions = [[] for _ in range(self.N)]

    # --------------------------
    # Один шаг симуляции

    def step(self):
        """
        Выполняю один переход НВЦМ по алгоритму Next-Event Simulation.

        Алгоритм (точная симуляция НВЦМ):
        --------------------------------------------------
        1. Текущее состояние = i.
        2. Суммарная интенсивность выхода: lambda_i = |q_ii| = -q_ii.
        3. Время пребывания в i: T ~ Exp(lambda_i).
               Метод обратной функции: T = -ln(U) / lambda_i, U ~ Uniform(0,1).
               Реализация: numpy.random.exponential(scale=1/lambda_i).
               Физический смысл: чем больше lambda_i (быстрее меняется),
               тем меньше ожидаемое время T.
        4. Вектор вероятностей перехода в другие состояния:
               p_ij = q_ij / lambda_i  (j != i),  p_ii = 0.
               Сумма = sum(q_ij/lambda_i, j!=i) = lambda_i/lambda_i = 1.
        5. Случайно выбираю следующее состояние j согласно p_ij.
        6. Обновляю total_time, time_in_state, history, running_fractions.
        7. Переходю в состояние j.
        --------------------------------------------------

        Возвращает:
            tuple (holding_time: float, next_state: int)
        """
        i = self.current_state

        # Шаг 2: суммарная интенсивность выхода из i.
        # Q[i,i] < 0, поэтому lambda_i = |Q[i,i]| = -Q[i,i] > 0.
        lambda_i = -self.Q[i, i]

        if lambda_i < 1e-12:
            # Поглощающее состояние: нет переходов из i.
            # Симулирую пребывание длиной 1 день и остаюсь в том же состоянии.
            # На практике при корректной Q это не должно происходить.
            holding_time = 1.0
            next_state   = i
        else:
            # Шаг 3: время пребывания из показательного распределения Exp(lambda_i).
            # numpy.random.exponential(scale=s) генерирует T ~ Exp(1/s),
            # то есть при scale = 1/lambda_i  получаем  T ~ Exp(lambda_i).
            # Математическое ожидание: E[T] = 1/lambda_i.
            holding_time = np.random.exponential(scale=1.0 / lambda_i)

            # Шаг 4: вектор вероятностей переходов из i в другие состояния.
            # p_ij = q_ij / lambda_i  для j != i;  p_ii = 0 (нельзя «перейти» в себя).
            probs = np.array([
                self.Q[i, j] / lambda_i if j != i else 0.0
                for j in range(self.N)
            ])

            # Нормирую вектор на случай накопленных численных ошибок.
            # Теоретически sum(probs) = 1 уже, но из-за float-арифметики
            # может быть 0.9999999... или 1.0000001...
            s = probs.sum()
            if s > 1e-12:
                probs /= s
            else:
                # Крайний случай: все интенсивности нулевые, кроме диагонали
                # (не должно случаться при корректной Q, но защита не лишняя)
                probs = np.ones(self.N) / self.N
                probs[i] = 0.0
                probs /= probs.sum()

            # Шаг 5: случайный выбор следующего состояния j.
            # np.random.choice(N, p=probs) возвращает индекс j
            # с вероятностью probs[j] = q_ij / lambda_i.
            next_state = int(np.random.choice(self.N, p=probs))

        # Шаг 6: обновляю статистику.

        # Записываю завершённый интервал пребывания в историю:
        # в момент total_time цепь находилась в состоянии i и пробыла там holding_time.
        self.history.append((self.total_time, i, holding_time))

        # Сдвигаю модельные часы вперёд на время пребывания
        self.total_time += holding_time

        # Накапливаю суммарное время в состоянии i
        self.time_in_state[i] += holding_time

        # Увеличиваю счётчик совершённых переходов
        self.n_transitions += 1

        # Обновляю бегущие доли накопленного времени:
        # running_fractions[k] = time_in_state[k] / total_time.
        # Именно эта величина сходится к pi[k] при n_transitions -> inf.
        for k in range(self.N):
            frac = self.time_in_state[k] / self.total_time if self.total_time > 1e-12 else 0.0
            self.running_fractions[k].append(frac)

        # Шаг 7: переходю в новое состояние
        self.current_state = next_state

        return holding_time, next_state

    # Математические расчёты

    def compute_stationary_distribution(self):
        """
        Вычисляю теоретическое стационарное распределение pi = (pi_0, pi_1, pi_2).

        Определение стационарного распределения НВЦМ:
        --------------------------------------------------
        Вектор-строка pi удовлетворяет уравнениям глобального баланса:

            pi * Q = 0    (вероятностный поток в состояние i = потоку из него)
            sum(pi) = 1   (условие нормировки)

        Физический смысл pi_i:
            Доля непрерывного времени, которую процесс проводит в состоянии i
            в долгосрочной перспективе (при t -> inf), независимо от X(0).

        Формально (эргодическая теорема для НВЦМ):
            lim_{T->inf} (1/T) * integral_0^T 1{X(t)=i} dt = pi_i  (п.н.)

        Метод решения:
        --------------------------------------------------
        Из pi * Q = 0 (pi - строка, Q - матрица N x N):
            (pi * Q)[j] = sum_i(pi[i] * Q[i,j]) = 0  для каждого j.

        В матричном виде (столбцовая запись):
            Q^T * pi_col = 0

        Поскольку уравнения pi*Q=0 линейно зависимы (сумма = 0),
        заменяю последнее уравнение на условие нормировки.
        Итоговая система A * pi_col = b:

            A = Q^T  с заменой последней строки на [1, 1, ..., 1]
            b = [0, ..., 0, 1]^T

        Решаю через numpy.linalg.solve (LU-разложение).

        Возвращает:
            np.ndarray: вектор pi длины N, pi[i] >= 0, sum(pi) = 1.
        """
        Q = self.Q
        n = self.N

        # Матрица системы: транспонирую Q для получения уравнений для pi
        A = Q.T.copy()

        # Правая часть: нулевой вектор
        b = np.zeros(n)

        # Заменяю последнюю строку A на условие нормировки: sum(pi) = 1.
        # Без этого система вырождена - у неё бесконечно много решений
        # (любое кратное pi тоже удовлетворяет pi*Q=0).
        A[-1, :] = 1.0
        b[-1]    = 1.0

        try:
            # Решаю систему методом LU-разложения (стандартный numpy)
            pi = np.linalg.solve(A, b)

            # Исправляю численные ошибки: теоретически pi[i] >= 0,
            # но из-за float-арифметики могут появиться -1e-15 и т.п.
            pi = np.maximum(pi, 0.0)

            # Перенормирую на случай численных отклонений от 1
            s = pi.sum()
            if s > 1e-12:
                pi /= s
            else:
                # Вырожденная матрица (например, все интенсивности нулевые)
                pi = np.ones(n) / n

        except np.linalg.LinAlgError:
            # Матрица A оказалась вырождена - возвращаю равномерное распределение
            pi = np.ones(n) / n

        return pi

    def get_empirical_fractions(self):
        """
        Возвращаю вектор эмпирических долей накопленного времени.

        empirical[i] = time_in_state[i] / total_time

        По эргодической теореме для НВЦМ:
            empirical[i]  --->  pi[i]  при total_time -> infinity.

        Именно эту сходимость я показываю на графике «Сходимость к Q-стационарному».

        Возвращает:
            np.ndarray: вектор длины N, sum = 1 (или нули, если нет данных).
        """
        if self.total_time < 1e-12:
            return np.zeros(self.N)
        return self.time_in_state / self.total_time

    # ---------------------
    # Сохранение в CSV

    def save_to_csv(self, folder='output'):
        """
        Сохраняю всю статистику симуляции в три CSV-файла.

        Файлы создаются с временной меткой, чтобы не перезаписывать
        результаты предыдущих запусков.

        Параметры:
            folder (str): путь к папке. Создаётся автоматически при отсутствии.

        Файлы:
            1. history_*.csv  - полная история переходов (момент, состояние, длительность)
            2. stats_*.csv    - сводная статистика: время в состояниях, эмпирика vs теория,
                                средние времена пребывания
            3. q_matrix_*.csv - матрица Q и стационарное распределение

        Возвращает:
            list[str]: список абсолютных путей к созданным файлам.
        """
        # Создаю папку (exist_ok=True - не бросает ошибку если уже есть)
        os.makedirs(folder, exist_ok=True)

        # Временная метка для уникальности имён
        ts = datetime.now().strftime('%Y%m%d_%H%M%S')

        created = []

        # Вычисляю статистику один раз - используется в нескольких файлах
        empirical  = self.get_empirical_fractions()
        stationary = self.compute_stationary_distribution()

        # Файл 1: полная история переходов
        history_path = os.path.join(folder, f'history_{ts}.csv')
        with open(history_path, 'w', newline='', encoding='utf-8-sig') as f:
            # utf-8-sig - BOM-маркер для корректного открытия кириллицы в Excel
            w = csv.writer(f)
            w.writerow([
                'Переход №',
                'Время входа (дн)',
                'Состояние (имя)',
                'Состояние (код 1-3)',
                'Длительность (дн)',
                'Время выхода (дн)',
            ])
            for idx, (t_in, state, dur) in enumerate(self.history, start=1):
                w.writerow([
                    idx,
                    f'{t_in:.6f}',
                    self.STATE_NAMES[state],
                    state + 1,            # 1-based: 1=Ясно, 2=Облачно, 3=Пасмурно
                    f'{dur:.6f}',
                    f'{t_in + dur:.6f}',  # t_выхода = t_входа + длительность
                ])
        created.append(os.path.abspath(history_path))

        # Файл 2: сводная статистика
        stats_path = os.path.join(folder, f'stats_{ts}.csv')
        with open(stats_path, 'w', newline='', encoding='utf-8-sig') as f:
            w = csv.writer(f)

            # Общая информация
            w.writerow(['=== Общая информация ==='])
            w.writerow(['Всего переходов',          self.n_transitions])
            w.writerow(['Суммарное время (дн)',      f'{self.total_time:.6f}'])
            w.writerow([])

            # Сравнение эмпирики с теоретическим стационарным распределением
            w.writerow(['=== Доли времени в состояниях ==='])
            w.writerow(['Состояние', 'Время (дн)', 'Эмпирич. доля',
                        'Теорет. доля (pi)', '|Отклонение|'])
            for i in range(self.N):
                deviation = abs(empirical[i] - stationary[i])
                w.writerow([
                    self.STATE_NAMES[i],
                    f'{self.time_in_state[i]:.4f}',
                    f'{empirical[i]:.6f}',
                    f'{stationary[i]:.6f}',
                    f'{deviation:.6f}',
                ])
            w.writerow([])

            # Среднее время пребывания в каждом состоянии
            # Для Exp(lambda_i): E[T_i] = 1 / lambda_i = 1 / |q_ii|
            w.writerow(['=== Средние времена пребывания (теория) ==='])
            w.writerow(['Состояние', 'lambda_i = |q_ii| (1/дн)', 'E[T_i] = 1/lambda_i (дн)'])
            for i in range(self.N):
                lam      = -self.Q[i, i]
                mean_t   = (1.0 / lam) if lam > 1e-12 else float('inf')
                w.writerow([self.STATE_NAMES[i], f'{lam:.6f}', f'{mean_t:.6f}'])
        created.append(os.path.abspath(stats_path))

        # Файл 3: матрица Q и стационарное распределение
        qmat_path = os.path.join(folder, f'q_matrix_{ts}.csv')
        with open(qmat_path, 'w', newline='', encoding='utf-8-sig') as f:
            w = csv.writer(f)
            w.writerow(['Q (строка=откуда, столбец=куда)'] + self.STATE_NAMES)
            for i in range(self.N):
                row = [self.STATE_NAMES[i]] + [f'{self.Q[i, j]:.6f}' for j in range(self.N)]
                w.writerow(row)
            w.writerow([])
            w.writerow(['Стационарное распределение pi (теория):'])
            w.writerow(['pi_' + name for name in self.STATE_NAMES])
            w.writerow([f'{stationary[i]:.6f}' for i in range(self.N)])
        created.append(os.path.abspath(qmat_path))

        return created
